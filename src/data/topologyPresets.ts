/**
 * Generates synthetic feature vectors for Random Forest training
 * (simulating historical node/edge security metrics and breach status)
 */
export function generateSyntheticTrainingSet(samplesCount = 200): FeatureVector[] {
  const dataset: FeatureVector[] = [];
  const seed = 42;
  
  // Simple pseudo-random function for deterministic dataset generation
  let currentSeed = seed;
  const pseudoRandom = () => {
    currentSeed = (currentSeed * 9301 + 49297) % 233280;
    return currentSeed / 233280;
  };

  for (let i = 0; i < samplesCount; i++) {
    const inDegree = Math.floor(pseudoRandom() * 6) + 1;
    const outDegree = Math.floor(pseudoRandom() * 6);
    const totalDegree = inDegree + outDegree;
    const maxCvss = Number((pseudoRandom() * 6 + 4).toFixed(1)); // 4.0 to 10.0
    const avgCvss = Number((maxCvss - pseudoRandom() * 2).toFixed(1));
    const vulnerabilityCount = Math.floor(pseudoRandom() * 5);
    const authRequiredRatio = Number(pseudoRandom().toFixed(2));
    const criticality = Math.floor(pseudoRandom() * 5) + 1;
    const highRiskPortCount = Math.floor(pseudoRandom() * 4);
    const centralityScore = Number((pseudoRandom() * 0.8 + 0.1).toFixed(3));

    // Calculate realistic ground-truth label based on weighted risk score
    const riskFactor =
      maxCvss * 0.3 +
      vulnerabilityCount * 0.8 +
      (1 - authRequiredRatio) * 2.5 +
      highRiskPortCount * 0.7 +
      centralityScore * 2.0 +
      criticality * 0.5;

    // Probability of compromise threshold
    const isCompromisedLabel = riskFactor > 6.5 ? 1 : 0;

    dataset.push({
      nodeId: `node-sample-${i + 1}`,
      inDegree,
      outDegree,
      totalDegree,
      maxCvss,
      avgCvss,
      vulnerabilityCount,
      authRequiredRatio,
      criticality,
      highRiskPortCount,
      centralityScore,
      isCompromisedLabel,
    });
  }

  return dataset;
}
